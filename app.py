import streamlit as st
import pandas as pd
import joblib
import os

st.set_page_config(
    page_title="Loan Approval Prediction",
    page_icon="🏦",
    layout="wide"
)

@st.cache_resource
def load_model():
    return joblib.load(
        os.path.join(os.path.dirname(__file__), "best_loan_model.pkl")
    )

model = load_model()

st.title("🏦 Loan Approval Prediction System")
st.write("Enter applicant information to predict loan approval status.")
st.info("For educational purposes only. This is not an actual bank decision.")

left, right = st.columns(2)

with left:
    st.subheader("Applicant Details")

    with st.form("loan_form"):
        dependents = st.number_input(
            "Number of Dependents", 0, 20, 2
        )
        education = st.selectbox(
            "Education", ["Graduate", "Not Graduate"]
        )
        self_employed = st.selectbox(
            "Self Employed", ["No", "Yes"]
        )
        income = st.number_input(
            "Annual Income", min_value=0, value=9600000, step=100000
        )
        loan_amount = st.number_input(
            "Loan Amount", min_value=0, value=29900000, step=100000
        )
        loan_term = st.number_input(
            "Loan Term (Years)", min_value=1, max_value=50, value=12
        )
        cibil = st.number_input(
            "CIBIL Score", min_value=0, max_value=1000, value=778
        )
        residential = st.number_input(
            "Residential Assets Value", min_value=0, value=2400000
        )
        commercial = st.number_input(
            "Commercial Assets Value", min_value=0, value=17600000
        )
        luxury = st.number_input(
            "Luxury Assets Value", min_value=0, value=22700000
        )
        bank = st.number_input(
            "Bank Asset Value", min_value=0, value=8000000
        )

        submitted = st.form_submit_button(
            "Predict Loan Approval",
            use_container_width=True
        )

with right:
    st.subheader("Prediction Result")

    if submitted:
        applicant = pd.DataFrame([{
            "no_of_dependents": dependents,
            "education": education,
            "self_employed": self_employed,
            "income_annum": income,
            "loan_amount": loan_amount,
            "loan_term": loan_term,
            "cibil_score": cibil,
            "residential_assets_value": residential,
            "commercial_assets_value": commercial,
            "luxury_assets_value": luxury,
            "bank_asset_value": bank
        }])

        prediction = int(model.predict(applicant)[0])

        if prediction == 1:
            st.success("## ✅ Loan Approved")
        else:
            st.error("## ❌ Loan Rejected")

        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(applicant)[0]
            st.metric(
                "Estimated model confidence",
                f"{max(probabilities):.1%}"
            )

        st.subheader("Applicant Summary")
        st.dataframe(
            applicant.T.rename(columns={0: "Value"}),
            use_container_width=True
        )
    else:
        st.write("Enter the details and click **Predict Loan Approval**.")

st.caption(
    "Predictions are generated by a machine-learning model trained "
    "on historical data. They are not guarantees of loan approval."
)
